#!/usr/bin/env node
/**
 * Regenerate convex/seedFixtures.ts from app/data/ JSON files.
 * Run from app/: node scripts/generate-seed-fixtures.mjs
 */

import { readFile, writeFile, readdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const appRoot = path.resolve(__dirname, '..')
const packsDir = path.join(appRoot, 'data', 'packs')

const packFiles = (await readdir(packsDir)).filter((f) => f.endsWith('.json'))
const SEED_PACKS = await Promise.all(
  packFiles.map(async (file) => {
    const packId = file.replace(/\.json$/, '')
    const manifest = JSON.parse(await readFile(path.join(packsDir, file), 'utf-8'))
    return { packId, manifest }
  }),
)

const SEED_EVENTS = JSON.parse(
  await readFile(path.join(appRoot, 'data', 'telemetry.json'), 'utf-8'),
)

const out = `// Auto-generated by scripts/generate-seed-fixtures.mjs — do not edit by hand
export const SEED_PACKS = ${JSON.stringify(SEED_PACKS, null, 2)} as const;
export const SEED_EVENTS = ${JSON.stringify(SEED_EVENTS, null, 2)} as const;
`

await writeFile(path.join(appRoot, 'convex', 'seedFixtures.ts'), out, 'utf-8')
console.log(`Wrote ${SEED_PACKS.length} packs and ${SEED_EVENTS.length} events to convex/seedFixtures.ts`)
